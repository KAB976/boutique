// Écriture minimale d'un classeur .xlsx (sans dépendance) : feuilles, texte, nombres, en-têtes en gras, formats monétaires.
import zlib from 'node:zlib';

const esc = (s) => String(s).replace(/[<>&"']/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;', "'": '&apos;' }[c])).replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');
const colName = (i) => { let s = ''; for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s; return s; };

/** Cellule : nombre, texte, ou { v, fmt:'money'|'int'|'pct', bold } */
function cellXml(ref, c) {
  if (c === null || c === undefined || c === '') return '';
  let v = c, style = 0;
  if (typeof c === 'object') { v = c.v; style = c.bold ? 1 : { money: 2, int: 3, pct: 4 }[c.fmt] ?? 0; if (c.bold && c.fmt === 'money') style = 5; }
  if (v === null || v === undefined || v === '') return '';
  if (typeof v === 'number' && Number.isFinite(v)) return `<c r="${ref}" s="${style}"><v>${v}</v></c>`;
  return `<c r="${ref}" s="${style}" t="inlineStr"><is><t xml:space="preserve">${esc(v)}</t></is></c>`;
}

function sheetXml(rows, widths = []) {
  const cols = widths.length ? `<cols>${widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>` : '';
  const body = rows.map((r, y) => `<row r="${y + 1}">${r.map((c, x) => cellXml(`${colName(x)}${y + 1}`, c)).join('')}</row>`).join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${cols}<sheetData>${body}</sheetData></worksheet>`;
}

